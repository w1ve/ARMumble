//! The Media Foundation H.264 encoder MFT.
//!
//! # Why this is more than a `ProcessInput`/`ProcessOutput` loop
//!
//! Hardware encoder MFTs are normally **asynchronous**. Such an MFT refuses work
//! with `MF_E_TRANSFORM_ASYNC_LOCKED` until the caller sets
//! `MF_TRANSFORM_ASYNC_UNLOCK`, and thereafter input and output are driven by
//! events (`METransformNeedInput`, `METransformHaveOutput`) rather than by calling
//! in whenever you like. Writing the synchronous flow would appear to work on any
//! machine that happens to expose a synchronous MFT and fail everywhere else.
//!
//! This encoder detects which model the MFT uses and drives whichever one applies,
//! so the same code works on Intel, NVIDIA and AMD.
//!
//! # Latency shape
//!
//! [`HwEncoder::encode`] returns `Option<EncodedFrame>` rather than a frame,
//! because an asynchronous encoder is a pipeline: the first submission or two can
//! legitimately produce nothing while it fills, with the output arriving on a
//! later call. Blocking until each frame's own output appeared would risk a
//! deadlock against an encoder that wants more input first, so instead outputs are
//! matched to submissions through a FIFO — correct here because low-latency H.264
//! has no frame reordering.
//!
//! `CODECAPI_AVLowLatencyMode` is requested, which is what keeps that pipeline one
//! or two frames deep instead of many.

