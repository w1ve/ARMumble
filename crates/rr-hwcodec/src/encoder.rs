/// Media Foundation counts time in 100 ns units.
const TICKS_PER_SECOND: i64 = 10_000_000;

/// Where the time in one [`HwEncoder::encode`] call went.
///
/// Exposed because "encode is slow" is not actionable. Staging a 4K frame into a
/// Media Foundation buffer is a 33 MiB copy and can rival the encode itself, so
/// knowing which phase dominates decides whether the next move is a zero-copy GPU
/// path or something else entirely.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct EncodeStats {
    /// Colour conversion if needed, plus the copy into a Media Foundation buffer.
    pub build: std::time::Duration,
    /// The `ProcessInput` call itself.
    pub submit: std::time::Duration,
    /// Pumping events and copying finished frames out.
    pub drain: std::time::Duration,
}

impl EncodeStats {
    /// Total time attributed across the three phases.
    #[must_use]
    pub fn total(&self) -> std::time::Duration {
        self.build + self.submit + self.drain
    }
}

/// How many events to read while waiting for one output before giving up and
/// letting the caller try again.
///
/// A bound rather than an open loop: an encoder that wants more input before
/// producing any would otherwise hang the caller forever.
const MAX_EVENT_WAIT: usize = 16;

/// Encoder tuning.
#[derive(Debug, Clone, Copy)]
pub struct HwEncoderSettings {
    /// Target bitrate in bits per second.
    pub bitrate_bps: u32,
    /// Target frame rate, which rate control uses to budget each frame.
    pub fps: u32,
    /// Whether to try BGRA input before NV12.
    ///
    /// BGRA avoids a CPU colour conversion, which is worth 11 ms a frame at 4K, so
    /// it is tried first by default. Set `false` to go straight to NV12, which is
    /// the format every hardware encoder genuinely supports — useful when a driver
    /// *accepts* a BGRA input type and then misbehaves, which is not a
    /// hypothetical.
    pub prefer_bgra: bool,
}

impl Default for HwEncoderSettings {
    fn default() -> Self {
        Self {
            // Matches rr-codec's software default, so switching encoders does not
            // silently change bandwidth.
            bitrate_bps: 8_000_000,
            fps: 30,
            prefer_bgra: true,
        }
    }
}

/// A hardware H.264 encoder.
pub struct HwEncoder {
    /// The MFT doing the work.
    transform: IMFTransform,
    /// Event source; `Some` only for asynchronous MFTs.
    events: Option<IMFMediaEventGenerator>,
    /// Codec configuration interface, when the MFT exposes one.
    codec_api: Option<ICodecAPI>,
    /// Which encoder was selected.
    info: EncoderInfo,
    /// Negotiated input layout, which decides whether we convert colour.
    layout: InputLayout,
    /// Frame width in pixels.
    width: u32,
    /// Frame height in pixels.
    height: u32,
    /// Reused NV12 staging buffer; empty when the MFT takes BGRA.
    scratch: Vec<u8>,
    /// Monotonic presentation timestamp in 100 ns units.
    timestamp: i64,
    /// Duration of one frame in 100 ns units.
    frame_duration: i64,
    /// Whether the MFT allocates its own output samples.
    provides_samples: bool,
    /// Size to allocate when it does not.
    output_size: u32,
    /// Sequence numbers of submitted frames, oldest first, matched to outputs in
    /// order. Valid because low-latency H.264 does not reorder frames.
    submitted: VecDeque<u64>,
    /// Outputs drained from the MFT but not yet returned to the caller.
    ready: VecDeque<EncodedFrame>,
    /// Set by [`HwEncoder::request_keyframe`]; cleared once applied.
    force_keyframe: bool,
    /// Kept so the output type can be rebuilt if the MFT asks to renegotiate.
    settings: HwEncoderSettings,
    /// Phase timings from the most recent encode.
    stats: EncodeStats,
}

impl std::fmt::Debug for HwEncoder {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("HwEncoder")
            .field("encoder", &self.info.name)
            .field("hardware", &self.info.hardware)
            .field("layout", &self.layout)
            .field("width", &self.width)
            .field("height", &self.height)
            .field("async", &self.events.is_some())
            .field("provides_samples", &self.provides_samples)
            .field("output_size", &self.output_size)
            .field("codec_api", &self.codec_api.is_some())
            .finish_non_exhaustive()
    }
}

impl HwEncoder {
    /// Create a hardware encoder for `width` x `height` frames.
    ///
    /// # Errors
    /// Returns [`HwCodecError::NoEncoder`] when the system has no hardware H.264
    /// encoder, or [`HwCodecError::Configuration`] when one exists but will not
    /// accept this geometry.
    pub fn new(width: u32, height: u32, settings: HwEncoderSettings) -> Result<Self> {
        if width == 0 || height == 0 || !width.is_multiple_of(2) || !height.is_multiple_of(2) {
            return Err(HwCodecError::UnsupportedFrame(format!(
                "{width}x{height}: H.264 4:2:0 needs non-zero, even dimensions"
            )));
        }

        let (transform, info) = activate_hardware_h264()?;
        let events = unlock_if_async(&transform)?;
        let codec_api = configure_codec_api(&transform, settings);

        // Order matters, and it is circular: the encoder will not accept an input
        // type until it knows what it is producing, but settling on an input type
        // can invalidate the output type it agreed to. Quick Sync then raises
        // MF_E_TRANSFORM_STREAM_CHANGE on the first `ProcessOutput`, mid-stream,
        // where it is far more awkward to handle.
        //
        // So: set output tentatively, negotiate input, then set output again to
        // finalise it. Doing the renegotiation up front means steady-state
        // encoding has no format changes to deal with.
        configure_output(&transform, width, height, settings)?;
        let layout = configure_input(&transform, width, height, settings)?;
        configure_output(&transform, width, height, settings)?;

        let (provides_samples, output_size) = output_stream_info(&transform)?;

        // SAFETY: both messages take a stream-less MFT command with a zero
        // parameter and borrow nothing from us.
        unsafe {
            transform
                .ProcessMessage(MFT_MESSAGE_NOTIFY_BEGIN_STREAMING, 0)
                .map_err(mf_err("NOTIFY_BEGIN_STREAMING"))?;
            transform
                .ProcessMessage(MFT_MESSAGE_NOTIFY_START_OF_STREAM, 0)
                .map_err(mf_err("NOTIFY_START_OF_STREAM"))?;
        }

        let fps = settings.fps.max(1);
        debug!(
            encoder = %info.name,
            ?layout,
            is_async = events.is_some(),
            provides_samples,
            "hardware encoder ready"
        );

        Ok(Self {
            transform,
            events,
            codec_api,
            info,
            layout,
            width,
            height,
            scratch: if layout.needs_cpu_conversion() {
                vec![0u8; nv12_len(width, height)]
            } else {
                Vec::new()
            },
            timestamp: 0,
            frame_duration: TICKS_PER_SECOND / i64::from(fps),
            provides_samples,
            output_size,
            submitted: VecDeque::new(),
            ready: VecDeque::new(),
            force_keyframe: false,
            settings,
            stats: EncodeStats::default(),
        })
    }

    /// The selected encoder.
    #[must_use]
    pub fn info(&self) -> &EncoderInfo {
        &self.info
    }

    /// The negotiated input layout.
    #[must_use]
    pub const fn input_layout(&self) -> InputLayout {
        self.layout
    }

    /// Where the time in the most recent [`HwEncoder::encode`] call went.
    #[must_use]
    pub const fn last_stats(&self) -> EncodeStats {
        self.stats
    }

    /// Whether this MFT is driven by events rather than direct calls.
    #[must_use]
    pub const fn is_async(&self) -> bool {
        self.events.is_some()
    }

    /// Frame dimensions this encoder was built for.
    #[must_use]
    pub const fn dimensions(&self) -> (u32, u32) {
        (self.width, self.height)
    }

    /// Ask for the next encoded frame to be an IDR.
    pub fn request_keyframe(&mut self) {
        self.force_keyframe = true;
    }

    /// Submit one frame and return an encoded frame if one is ready.
    ///
    /// Returns `None` while the pipeline fills; the output appears on a later
    /// call. Call [`HwEncoder::flush`] at the end of a stream to drain the rest.
    ///
    /// # Errors
    /// Returns [`HwCodecError`] if the frame does not match the configured
    /// geometry, or if Media Foundation rejects the submission.
    pub fn encode(&mut self, frame: &rr_capture::Frame) -> Result<Option<EncodedFrame>> {
        if frame.width != self.width || frame.height != self.height {
            return Err(HwCodecError::UnsupportedFrame(format!(
                "frame {}x{} does not match encoder {}x{}",
                frame.width, frame.height, self.width, self.height
            )));
        }

        let t_build = std::time::Instant::now();
        let sample = self.build_sample(frame)?;
        let build = t_build.elapsed();
        if self.force_keyframe {
            self.apply_force_keyframe();
        }

        // An async MFT must be asked for input before it will take any. This is the
        // one place we block, and it is the right place: it is backpressure, and it
        // only waits when the encoder is genuinely full.
        if self.is_async() {
            self.pump_until_need_input()?;
        }

        // SAFETY: `sample` is a live `IMFSample` we just built; `ProcessInput`
        // takes a borrowed reference and retains it itself if it needs to.
        let t_submit = std::time::Instant::now();
        unsafe { self.transform.ProcessInput(0, &sample, 0) }.map_err(mf_err("ProcessInput"))?;
        let submit = t_submit.elapsed();
        self.submitted.push_back(frame.sequence);

        // Collect whatever is *already* finished, without waiting for this frame's
        // own output.
        //
        // Waiting here instead would serialise the pipeline: measured at 3840x2160,
        // blocking for each frame's output cost 41.9 ms a frame, against ~12 ms of
        // actual encoder throughput. A hardware encoder is a pipeline and has to be
        // used as one — submit, carry on, pick the output up when it appears.
        let t_drain = std::time::Instant::now();
        if self.is_async() {
            self.drain_available()?;
        } else {
            self.drain_sync()?;
        }
        self.stats = EncodeStats {
            build,
            submit,
            drain: t_drain.elapsed(),
        };
        Ok(self.ready.pop_front())
    }

    /// Drain everything the encoder still holds.
    ///
    /// # Errors
    /// Returns [`HwCodecError`] if the drain messages or output reads fail.
    pub fn flush(&mut self) -> Result<Vec<EncodedFrame>> {
        // SAFETY: stream-less MFT commands with a zero parameter.
        unsafe {
            self.transform
                .ProcessMessage(MFT_MESSAGE_NOTIFY_END_OF_STREAM, 0)
                .map_err(mf_err("NOTIFY_END_OF_STREAM"))?;
            self.transform
                .ProcessMessage(MFT_MESSAGE_COMMAND_DRAIN, 0)
                .map_err(mf_err("COMMAND_DRAIN"))?;
        }

        if self.is_async() {
            // Draining an async MFT is event-driven like everything else: it
            // answers remaining frames with `METransformHaveOutput` and finishes
            // with `METransformDrainComplete`. Polling `ProcessOutput` directly
            // here — which an earlier version did — is an out-of-turn call and
            // fails the whole flush with a bare E_UNEXPECTED after every frame had
            // encoded perfectly well.
            for _ in 0..MAX_EVENT_WAIT * 4 {
                match self.next_event()? {
                    Some(EventKind::HaveOutput) => {
                        let _ = self.collect_once()?;
                    }
                    Some(EventKind::DrainComplete) | None => break,
                    Some(EventKind::NeedInput | EventKind::Other) => {}
                }
            }
        } else {
            // Bounded: a drained encoder stops producing, and a bound means a
            // misbehaving one cannot hang shutdown.
            for _ in 0..MAX_EVENT_WAIT {
                if !self.collect_once()? {
                    break;
                }
            }
        }
        Ok(self.ready.drain(..).collect())
    }

    /// Wrap the frame's pixels in an `IMFSample`, converting colour if needed.
    fn build_sample(&mut self, frame: &rr_capture::Frame) -> Result<IMFSample> {
        let packed_row = self.width as usize * 4;
        let (bytes, len): (&[u8], usize) = match self.layout {
            InputLayout::Nv12 => {
                // Honour the capture backend's channel order: DXGI gives BGRA,
                // `xcap` gives RGBA. Getting this wrong swaps red and blue, which
                // is a subtle and very annoying bug to chase from a screenshot.
                let convert = match frame.format {
                    rr_capture::PixelFormat::Bgra8 => bgra_to_nv12,
                    rr_capture::PixelFormat::Rgba8 => rgba_to_nv12,
                };
                let n = convert(
                    &frame.data,
                    self.width,
                    self.height,
                    frame.stride,
                    &mut self.scratch,
                )
                .ok_or_else(|| {
                    HwCodecError::UnsupportedFrame(
                        "colour conversion rejected the frame geometry".to_owned(),
                    )
                })?;
                (&self.scratch, n)
            }
            InputLayout::Bgra32 if frame.stride == packed_row => {
                let n = packed_row * self.height as usize;
                (frame.data.get(..n).unwrap_or(&frame.data), n)
            }
            InputLayout::Bgra32 => {
                // Captured frames may carry row padding; the MFT wants rows packed.
                repack_rows(
                    &frame.data,
                    frame.stride,
                    packed_row,
                    self.height,
                    &mut self.scratch,
                )?;
                let n = self.scratch.len();
                (&self.scratch, n)
            }
        };

        let cb = u32::try_from(len).map_err(|_| {
            HwCodecError::UnsupportedFrame("frame larger than a u32 length".to_owned())
        })?;

        // SAFETY: allocates a Media Foundation buffer of the requested size and
        // returns an owned, reference-counted handle.
        let buffer = unsafe { MFCreateMemoryBuffer(cb) }.map_err(mf_err("MFCreateMemoryBuffer"))?;

        let mut dst: *mut u8 = std::ptr::null_mut();
        // SAFETY: `Lock` writes a pointer to at least `cb` writable bytes into
        // `dst`. We pass `None` for the two optional length outputs because `cb`
        // is already known. Paired with `Unlock` below on every path.
        unsafe { buffer.Lock(&raw mut dst, None, None) }.map_err(mf_err("IMFMediaBuffer::Lock"))?;
        if dst.is_null() {
            // SAFETY: the buffer is locked; releasing it is required before the
            // early return.
            let _ = unsafe { buffer.Unlock() };
            return Err(HwCodecError::Mf {
                operation: "IMFMediaBuffer::Lock",
                source_message: "returned a null pointer".to_owned(),
            });
        }
        // SAFETY: `dst` points to at least `cb` == `len` writable bytes just
        // obtained from `Lock`, `bytes` holds exactly `len` readable bytes, and
        // the two allocations are distinct so they cannot overlap.
        unsafe {
            std::ptr::copy_nonoverlapping(bytes.as_ptr(), dst, len);
        }
        // SAFETY: balances the `Lock` above; `dst` is not used afterwards.
        unsafe { buffer.Unlock() }.map_err(mf_err("IMFMediaBuffer::Unlock"))?;

        // SAFETY: tells the buffer how much of its capacity is valid. Without
        // this the encoder reads a zero-length buffer.
        unsafe { buffer.SetCurrentLength(cb) }.map_err(mf_err("SetCurrentLength"))?;

        // SAFETY: creates an owned sample, then attaches the buffer and sets its
        // timing. All arguments are owned values or plain integers.
        let sample = unsafe { MFCreateSample() }.map_err(mf_err("MFCreateSample"))?;
        unsafe {
            sample.AddBuffer(&buffer).map_err(mf_err("AddBuffer"))?;
            sample
                .SetSampleTime(self.timestamp)
                .map_err(mf_err("SetSampleTime"))?;
            sample
                .SetSampleDuration(self.frame_duration)
                .map_err(mf_err("SetSampleDuration"))?;
        }
        self.timestamp += self.frame_duration;
        Ok(sample)
    }

    /// Ask the encoder to make the next frame an IDR.
    ///
    /// Best effort: an MFT without `ICodecAPI`, or one that rejects the property,
    /// simply keeps its own keyframe cadence. Losing a requested keyframe degrades
    /// a late-joining viewer's start-up time, which is not worth failing the
    /// encode over.
    fn apply_force_keyframe(&mut self) {
        let Some(api) = self.codec_api.as_ref() else {
            return;
        };
        let value = VARIANT::from(1u32);
        // SAFETY: `SetValue` reads the GUID and the VARIANT by pointer; both are
        // live locals for the duration of the call, and `VARIANT` cleans itself up
        // on drop.
        let set = unsafe {
            api.SetValue(
                &windows::Win32::Media::MediaFoundation::CODECAPI_AVEncVideoForceKeyFrame,
                &raw const value,
            )
        };
        match set {
            Ok(()) => self.force_keyframe = false,
            Err(e) => warn!(error = %e, "encoder would not force a keyframe"),
        }
    }

    /// Read events until the MFT asks for input, banking any output seen.
    fn pump_until_need_input(&mut self) -> Result<()> {
        for _ in 0..MAX_EVENT_WAIT {
            match self.next_event()? {
                Some(EventKind::NeedInput) => return Ok(()),
                Some(EventKind::HaveOutput) => {
                    let _ = self.collect_once()?;
                }
                Some(EventKind::Other) => {}
                // A drained encoder will never ask for input again.
                Some(EventKind::DrainComplete) | None => break,
            }
        }
        // Not an error: submitting anyway is harmless, and `ProcessInput` will
        // report `MF_E_NOTACCEPTING` if the encoder genuinely cannot take it.
        Ok(())
    }

    /// Bank every output that is ready right now, without waiting for more.
    ///
    /// This is what keeps the pipeline full: submission does not stall on the
    /// encoder finishing the frame just handed to it.
    fn drain_available(&mut self) -> Result<()> {
        // Generously bounded. The loop normally ends because no event is waiting;
        // the bound only stops a pathological encoder from spinning here forever.
        for _ in 0..MAX_EVENT_WAIT * 4 {
            match self.next_event_nowait()? {
                Some(EventKind::HaveOutput) => {
                    let _ = self.collect_once()?;
                }
                Some(EventKind::NeedInput | EventKind::Other) => {}
                // Either nothing is waiting, or the stream has ended.
                Some(EventKind::DrainComplete) | None => break,
            }
        }
        Ok(())
    }

    /// Read one event, blocking until one arrives.
    fn next_event(&self) -> Result<Option<EventKind>> {
        self.read_event(MEDIA_EVENT_GENERATOR_GET_EVENT_FLAGS(0))
    }

    /// Read one event only if one is already queued.
    fn next_event_nowait(&self) -> Result<Option<EventKind>> {
        // `MF_EVENT_FLAG_NO_WAIT`: return immediately rather than blocking.
        self.read_event(MEDIA_EVENT_GENERATOR_GET_EVENT_FLAGS(1))
    }

    /// Read one event, classifying it.
    fn read_event(&self, flags: MEDIA_EVENT_GENERATOR_GET_EVENT_FLAGS) -> Result<Option<EventKind>> {
        let Some(events) = self.events.as_ref() else {
            return Ok(None);
        };
        // SAFETY: the MFT is alive for as long as `self` is, and the returned event
        // is owned. An error means no event is available — either because the
        // no-wait flag was set and the queue is empty, or because the generator has
        // shut down. Both are normal, not failures.
        let Ok(event) = (unsafe { events.GetEvent(flags) }) else {
            return Ok(None);
        };
        // SAFETY: reads the event's type tag; the event is live.
        let kind = unsafe { event.GetType() }.map_err(mf_err("IMFMediaEvent::GetType"))?;
        let classified = if kind == METransformNeedInput.0.unsigned_abs() {
            EventKind::NeedInput
        } else if kind == METransformHaveOutput.0.unsigned_abs() {
            EventKind::HaveOutput
        } else if kind == METransformDrainComplete.0.unsigned_abs() {
            EventKind::DrainComplete
        } else {
            EventKind::Other
        };
        debug!(raw = kind, kind = classified.name(), "MFT event");
        Ok(Some(classified))
    }

    /// Pull outputs from a synchronous MFT until it wants more input.
    fn drain_sync(&mut self) -> Result<()> {
        for _ in 0..MAX_EVENT_WAIT {
            if !self.collect_once()? {
                break;
            }
        }
        Ok(())
    }

    /// Re-agree the output format after the MFT reports a stream change.
    ///
    /// Takes the encoder's own preferred output type where possible, since it just
    /// told us the previous one no longer applies, and falls back to rebuilding
    /// ours. Also refreshes the output buffer sizing, which can change with the
    /// format.
    fn renegotiate_output(&mut self) -> Result<()> {
        // Start from the encoder's own preferred type — it just told us the
        // previous one no longer applies — but overlay the geometry, rate and
        // bitrate we actually need, since a bare preference may omit them.
        // SAFETY: reads the transform's first preferred output type; an absent
        // index is reported as an error rather than being undefined.
        if let Ok(preferred) = unsafe { self.transform.GetOutputAvailableType(0, 0) } {
            // SAFETY: writes our required attributes into a type we now own, then
            // hands it back for validation.
            let applied = unsafe {
                preferred
                    .SetUINT64(&MF_MT_FRAME_SIZE, pack_u32_pair(self.width, self.height))
                    .and_then(|()| {
                        preferred.SetUINT64(
                            &MF_MT_FRAME_RATE,
                            pack_u32_pair(self.settings.fps.max(1), 1),
                        )
                    })
                    .and_then(|()| {
                        preferred.SetUINT32(&MF_MT_AVG_BITRATE, self.settings.bitrate_bps)
                    })
                    .and_then(|()| self.transform.SetOutputType(0, &preferred, 0))
            };
            if applied.is_ok() {
                debug!("renegotiated output type from the encoder's preference");
                let (provides, size) = output_stream_info(&self.transform)?;
                self.provides_samples = provides;
                self.output_size = size;
                return Ok(());
            }
        }

        // Fall back to re-applying exactly what we asked for originally.
        configure_output(&self.transform, self.width, self.height, self.settings)?;
        let (provides, size) = output_stream_info(&self.transform)?;
        self.provides_samples = provides;
        self.output_size = size;
        warn!("rebuilt our own output type after a stream change");
        Ok(())
    }

    /// Try to take one encoded frame from the MFT.
    ///
    /// Returns `false` when the encoder has nothing to give, which is the normal
    /// way out of a drain loop rather than an error.
    fn collect_once(&mut self) -> Result<bool> {
        match self.try_process_output()? {
            OutputAttempt::Frame(frame) => {
                self.ready.push_back(frame);
                Ok(true)
            }
            OutputAttempt::Nothing => Ok(false),
            // A format change consumes the `METransformHaveOutput` that brought us
            // here, so renegotiate and wait for the next event rather than calling
            // `ProcessOutput` again — an async MFT answers an out-of-turn call with
            // a bare E_UNEXPECTED. This should not normally fire at all, since the
            // output type is finalised during construction.
            OutputAttempt::StreamChange => {
                self.renegotiate_output()?;
                Ok(false)
            }
        }
    }

    /// One `ProcessOutput` call, classified.
    fn try_process_output(&mut self) -> Result<OutputAttempt> {
        let mut out = MFT_OUTPUT_DATA_BUFFER {
            dwStreamID: 0,
            ..Default::default()
        };

        // An MFT that does not allocate its own samples expects us to supply one.
        //
        // Asynchronous MFTs are required to allocate their own, and handing one to
        // an async MFT anyway is rejected with a bare E_UNEXPECTED — so never do it,
        // regardless of what `GetOutputStreamInfo` reported. It can be queried
        // before type negotiation completes and answer for a state the encoder is
        // no longer in.
        let own_sample = if self.provides_samples || self.is_async() {
            None
        } else {
            // SAFETY: both calls allocate owned Media Foundation objects.
            let s = unsafe { MFCreateSample() }.map_err(mf_err("MFCreateSample(output)"))?;
            let b = unsafe { MFCreateMemoryBuffer(self.output_size) }
                .map_err(mf_err("MFCreateMemoryBuffer(output)"))?;
            // SAFETY: attaches our buffer to our sample; both are live.
            unsafe { s.AddBuffer(&b) }.map_err(mf_err("AddBuffer(output)"))?;
            Some(s)
        };
        if let Some(s) = own_sample.as_ref() {
            out.pSample = std::mem::ManuallyDrop::new(Some(s.clone()));
        }

        let mut status: u32 = 0;
        // SAFETY: `ProcessOutput` reads and writes the single-element slice we
        // own, and writes the status word. On success it may replace `pSample`
        // with its own sample, which we take ownership of below.
        let result = unsafe {
            self.transform
                .ProcessOutput(0, std::slice::from_mut(&mut out), &raw mut status)
        };
        debug!(
            ok = result.is_ok(),
            status,
            buffer_status = out.dwStatus,
            "ProcessOutput"
        );

        // Take the sample out regardless of outcome, so the ManuallyDrop field
        // never leaks a reference.
        let produced = std::mem::ManuallyDrop::into_inner(std::mem::replace(
            &mut out.pSample,
            std::mem::ManuallyDrop::new(None),
        ));
        // `pEvents` is an optional collection the MFT may attach; dropping it
        // releases it.
        let events = std::mem::ManuallyDrop::into_inner(std::mem::replace(
            &mut out.pEvents,
            std::mem::ManuallyDrop::new(None),
        ));
        drop(events);

        match result {
            Ok(()) => {}
            Err(e) if e.code() == MF_E_TRANSFORM_NEED_MORE_INPUT => {
                return Ok(OutputAttempt::Nothing)
            }
            // Part of the MFT contract, not a failure: once the input type is
            // known the encoder may want to restate what it will produce. Intel's
            // Quick Sync MFT does exactly this on the first output after a BGRA
            // input type is set.
            Err(e) if e.code() == MF_E_TRANSFORM_STREAM_CHANGE => {
                return Ok(OutputAttempt::StreamChange)
            }
            Err(e) => {
                return Err(HwCodecError::Mf {
                    operation: "ProcessOutput",
                    source_message: e.to_string(),
                })
            }
        }

        let Some(sample) = produced else {
            return Ok(OutputAttempt::Nothing);
        };
        let (data, is_keyframe) = read_sample(&sample)?;
        if data.is_empty() {
            return Ok(OutputAttempt::Nothing);
        }
        let sequence = self.submitted.pop_front().unwrap_or_default();
        Ok(OutputAttempt::Frame(EncodedFrame {
            data,
            is_keyframe,
            sequence,
        }))
    }
}

/// Outcome of a single `ProcessOutput` call.
enum OutputAttempt {
    /// An encoded frame came out.
    Frame(EncodedFrame),
    /// Nothing available: the encoder wants more input, or produced an empty
    /// sample.
    Nothing,
    /// The MFT wants the output format renegotiated before it will produce.
    StreamChange,
}

impl Drop for HwEncoder {
    fn drop(&mut self) {
        // Tell the MFT the stream is over so the driver can release its queues.
        // Errors are meaningless here; the object is going away either way.
        // SAFETY: a stream-less MFT command with a zero parameter, on a transform
        // that is still alive until this function returns.
        let _ = unsafe {
            self.transform
                .ProcessMessage(MFT_MESSAGE_NOTIFY_END_OF_STREAM, 0)
        };
    }
}

/// Copy `height` rows of `packed` bytes each out of a padded buffer.
///
/// Reuses `dst`'s allocation across frames; at 4K a fresh 33 MiB allocation per
/// frame would cost more than the copy.
fn repack_rows(
    src: &[u8],
    stride: usize,
    packed: usize,
    height: u32,
    dst: &mut Vec<u8>,
) -> Result<()> {
    dst.clear();
    dst.reserve(packed * height as usize);
    for y in 0..height as usize {
        let start = y * stride;
        let row = src.get(start..start + packed).ok_or_else(|| {
            HwCodecError::UnsupportedFrame("frame shorter than its declared geometry".to_owned())
        })?;
        dst.extend_from_slice(row);
    }
    Ok(())
}

/// Which of the three events we care about arrived.
#[derive(Clone, Copy)]
enum EventKind {
    /// The MFT will accept a frame.
    NeedInput,
    /// The MFT has an encoded frame waiting.
    HaveOutput,
    /// The MFT has finished draining and will produce nothing more.
    DrainComplete,
    /// Something we do not act on.
    Other,
}

impl EventKind {
    /// A label for logs.
    const fn name(self) -> &'static str {
        match self {
            Self::NeedInput => "NeedInput",
            Self::HaveOutput => "HaveOutput",
            Self::DrainComplete => "DrainComplete",
            Self::Other => "other",
        }
    }
}

/// Unlock an asynchronous MFT and return its event source.
///
/// A synchronous MFT yields `Ok(None)`, which is what makes the rest of the
/// encoder model-agnostic.
fn unlock_if_async(transform: &IMFTransform) -> Result<Option<IMFMediaEventGenerator>> {
    // SAFETY: returns an owned attribute store belonging to the transform.
    // No attribute store at all means there is no async support to unlock.
    let Ok(attrs) = (unsafe { transform.GetAttributes() }) else {
        return Ok(None);
    };

    // SAFETY: reads a u32 attribute by GUID; absence is reported as an error
    // rather than written through, so the default below is the correct reading.
    let is_async = unsafe { attrs.GetUINT32(&MF_TRANSFORM_ASYNC) }.unwrap_or(0) == 1;
    if !is_async {
        debug!("MFT is synchronous");
        return Ok(None);
    }

    // SAFETY: sets a u32 attribute by GUID on the transform's own store. This is
    // the documented handshake that makes an async MFT usable; without it every
    // call returns MF_E_TRANSFORM_ASYNC_LOCKED.
    unsafe { attrs.SetUINT32(&MF_TRANSFORM_ASYNC_UNLOCK, 1) }
        .map_err(mf_err("MF_TRANSFORM_ASYNC_UNLOCK"))?;

    let generator = transform
        .cast::<IMFMediaEventGenerator>()
        .map_err(mf_err("cast to IMFMediaEventGenerator"))?;
    debug!("MFT is asynchronous and now unlocked");
    Ok(Some(generator))
}

/// Request low-latency behaviour and a predictable bitrate.
///
/// Returns the interface for later keyframe requests. Every property here is
/// best effort: encoders differ in what they expose, and a missing knob should not
/// stop us encoding.
fn configure_codec_api(transform: &IMFTransform, settings: HwEncoderSettings) -> Option<ICodecAPI> {
    let api = transform.cast::<ICodecAPI>().ok()?;

    // Low latency is the whole point: it disables lookahead and B-frames, which
    // otherwise add frames of delay for compression we do not want to pay for.
    let on = VARIANT::from(true);
    // SAFETY: `SetValue` reads the GUID and VARIANT through pointers that are
    // live locals for the call's duration.
    if let Err(e) = unsafe {
        api.SetValue(
            &windows::Win32::Media::MediaFoundation::CODECAPI_AVLowLatencyMode,
            &raw const on,
        )
    } {
        warn!(error = %e, "encoder does not support low-latency mode");
    }

    let bitrate = VARIANT::from(settings.bitrate_bps);
    // SAFETY: as above.
    if let Err(e) = unsafe {
        api.SetValue(
            &windows::Win32::Media::MediaFoundation::CODECAPI_AVEncCommonMeanBitRate,
            &raw const bitrate,
        )
    } {
        warn!(error = %e, "encoder would not take a mean bitrate");
    }

    Some(api)
}

/// Build and apply the H.264 output media type.
fn configure_output(
    transform: &IMFTransform,
    width: u32,
    height: u32,
    settings: HwEncoderSettings,
) -> Result<()> {
    // SAFETY: allocates an owned, empty media type.
    let ty = unsafe { MFCreateMediaType() }.map_err(mf_err("MFCreateMediaType(output)"))?;
    // SAFETY: each setter writes one attribute by GUID into the type we own; the
    // GUID constants are static and the helpers only read their arguments.
    unsafe {
        ty.SetGUID(&MF_MT_MAJOR_TYPE, &MFMediaType_Video)
            .map_err(mf_err("output MF_MT_MAJOR_TYPE"))?;
        ty.SetGUID(&MF_MT_SUBTYPE, &MFVideoFormat_H264)
            .map_err(mf_err("output MF_MT_SUBTYPE"))?;
        ty.SetUINT32(&MF_MT_AVG_BITRATE, settings.bitrate_bps)
            .map_err(mf_err("output MF_MT_AVG_BITRATE"))?;
        ty.SetUINT32(
            &MF_MT_INTERLACE_MODE,
            MFVideoInterlace_Progressive.0.unsigned_abs(),
        )
        .map_err(mf_err("output MF_MT_INTERLACE_MODE"))?;
        ty.SetUINT64(&MF_MT_FRAME_SIZE, pack_u32_pair(width, height))
            .map_err(mf_err("output MF_MT_FRAME_SIZE"))?;
        ty.SetUINT64(&MF_MT_FRAME_RATE, pack_u32_pair(settings.fps.max(1), 1))
            .map_err(mf_err("output MF_MT_FRAME_RATE"))?;
        ty.SetUINT64(&MF_MT_PIXEL_ASPECT_RATIO, pack_u32_pair(1, 1))
            .map_err(mf_err("output MF_MT_PIXEL_ASPECT_RATIO"))?;
        transform
            .SetOutputType(0, &ty, 0)
            .map_err(mf_err("SetOutputType"))?;
    }
    Ok(())
}

/// Negotiate the input format, preferring one that needs no CPU conversion.
///
/// Asks the MFT what it will take rather than guessing. BGRA first: an encoder
/// that accepts it converts on the GPU as part of encoding, which at 4K saves
/// 11 ms a frame against doing it ourselves.
fn configure_input(
    transform: &IMFTransform,
    width: u32,
    height: u32,
    settings: HwEncoderSettings,
) -> Result<InputLayout> {
    let fps = settings.fps;
    let bgra_first = [
        (MFVideoFormat_ARGB32, InputLayout::Bgra32),
        (MFVideoFormat_RGB32, InputLayout::Bgra32),
        (MFVideoFormat_NV12, InputLayout::Nv12),
    ];
    let nv12_only = [
        (MFVideoFormat_NV12, InputLayout::Nv12),
        (MFVideoFormat_ARGB32, InputLayout::Bgra32),
        (MFVideoFormat_RGB32, InputLayout::Bgra32),
    ];
    let preferences = if settings.prefer_bgra {
        bgra_first
    } else {
        nv12_only
    };

    let offered = offered_input_subtypes(transform);
    debug!(count = offered.len(), "encoder input types offered");
    for (subtype, layout) in preferences {
        if !offered.is_empty() && !offered.contains(&subtype) {
            continue;
        }
        // SAFETY: allocates an owned media type and writes attributes into it.
        let ty = unsafe { MFCreateMediaType() }.map_err(mf_err("MFCreateMediaType(input)"))?;
        // SAFETY: as in `configure_output`.
        let built = unsafe {
            ty.SetGUID(&MF_MT_MAJOR_TYPE, &MFMediaType_Video)
                .and_then(|()| ty.SetGUID(&MF_MT_SUBTYPE, &subtype))
                .and_then(|()| {
                    ty.SetUINT32(
                        &MF_MT_INTERLACE_MODE,
                        MFVideoInterlace_Progressive.0.unsigned_abs(),
                    )
                })
                .and_then(|()| ty.SetUINT64(&MF_MT_FRAME_SIZE, pack_u32_pair(width, height)))
                .and_then(|()| ty.SetUINT64(&MF_MT_FRAME_RATE, pack_u32_pair(fps.max(1), 1)))
                .and_then(|()| ty.SetUINT64(&MF_MT_PIXEL_ASPECT_RATIO, pack_u32_pair(1, 1)))
        };
        if let Err(e) = built {
            warn!(error = %e, "could not build input type, trying next");
            continue;
        }
        // SAFETY: hands the transform a borrowed media type it validates and
        // copies from.
        if unsafe { transform.SetInputType(0, &ty, 0) }.is_ok() {
            debug!(?layout, "negotiated encoder input layout");
            return Ok(layout);
        }
    }
    Err(HwCodecError::Configuration(format!(
        "no usable input format for {width}x{height}; encoder offered {} types",
        offered.len()
    )))
}

/// Subtypes the MFT advertises for input.
///
/// An empty result is not an error: some MFTs decline to enumerate and simply
/// accept or reject whatever `SetInputType` is given, which the caller handles by
/// trying its preferences in order.
fn offered_input_subtypes(transform: &IMFTransform) -> Vec<windows::core::GUID> {
    let mut out = Vec::new();
    for index in 0..32u32 {
        // SAFETY: reads the index-th available input type; an out-of-range index
        // is reported as an error rather than being undefined.
        let available = unsafe { transform.GetInputAvailableType(0, index) };
        let Ok(ty) = available else { break };
        // SAFETY: reads one GUID attribute from a type we now own.
        if let Ok(subtype) = unsafe { ty.GetGUID(&MF_MT_SUBTYPE) } {
            out.push(subtype);
        }
    }
    out
}

/// Whether the MFT allocates output samples, and how big ours must be if not.
fn output_stream_info(transform: &IMFTransform) -> Result<(bool, u32)> {
    // SAFETY: fills in a plain descriptor struct for stream 0.
    let info = unsafe { transform.GetOutputStreamInfo(0) }
        .map_err(mf_err("GetOutputStreamInfo"))?;
    let provides = info.dwFlags & MFT_OUTPUT_STREAM_PROVIDES_SAMPLES.0.unsigned_abs() != 0;
    // A floor, because some MFTs report zero and expect the caller to choose.
    let size = info.cbSize.max(1 << 20);
    Ok((provides, size))
}

/// Copy an encoded sample's bytes out, and note whether it is a keyframe.
fn read_sample(sample: &IMFSample) -> Result<(Vec<u8>, bool)> {
    // SAFETY: flattens any multi-buffer sample into one buffer we own. Needed
    // because an encoder may legitimately split an access unit across buffers.
    let buffer = unsafe { sample.ConvertToContiguousBuffer() }
        .map_err(mf_err("ConvertToContiguousBuffer"))?;

    let mut ptr: *mut u8 = std::ptr::null_mut();
    let mut len: u32 = 0;
    // SAFETY: `Lock` writes a readable pointer into `ptr` and the valid byte
    // count into `len`. Paired with `Unlock` on every path below.
    unsafe { buffer.Lock(&raw mut ptr, None, Some(&raw mut len)) }
        .map_err(mf_err("output Lock"))?;

    let data = if ptr.is_null() || len == 0 {
        Vec::new()
    } else {
        // SAFETY: `ptr` points to `len` initialised, readable bytes for as long as
        // the buffer stays locked, which it does until the `Unlock` below. The
        // copy ends before then.
        unsafe { std::slice::from_raw_parts(ptr, len as usize) }.to_vec()
    };

    // SAFETY: balances the `Lock`; `ptr` is not used afterwards.
    unsafe { buffer.Unlock() }.map_err(mf_err("output Unlock"))?;

    // SAFETY: reads one optional u32 attribute; absence is an error return, which
    // is why the default is applied here rather than trusting an out-param.
    let is_keyframe = unsafe { sample.GetUINT32(&MFSampleExtension_CleanPoint) }.unwrap_or(0) == 1;
    Ok((data, is_keyframe))
}
