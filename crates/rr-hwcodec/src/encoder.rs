/// Pack two 32-bit values into the single 64-bit attribute Media Foundation uses
/// for sizes and ratios: high word first.
///
/// `MFSetAttributeSize` and `MFSetAttributeRatio` are inline helpers in the C
/// headers and are not generated by `windows-rs`, so the packing is done here.
const fn pack_u32_pair(high: u32, low: u32) -> u64 {
    ((high as u64) << 32) | (low as u64)
}

